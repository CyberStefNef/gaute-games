// Build the shared host runtime, never the game payload. Run after renderer changes.
import { build } from 'vite-plus';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';
const file = fileURLToPath(import.meta.url);
const root = path.resolve(path.dirname(file), '..');
const require = createRequire(import.meta.url);
const threeRoot = path.resolve(path.dirname(require.resolve('three')), '..');
export function scene3dRuntimeHash() {
  const hash = createHash('sha256');
  for (const name of [
    'scene3d-core.ts',
    'scene3d-batches.ts',
    'scene3d-gestures.ts',
    'scene3d-browser.ts',
    'scene3d-native-proxy.ts',
    'scene3d-protocol.ts',
    'glb.mjs',
  ])
    hash.update(readFileSync(path.join(root, 'sdk', name)));
  hash.update(readFileSync(file));
  hash.update(readFileSync(path.join(threeRoot, 'package.json')));
  return hash.digest('hex');
}
if (process.argv[1] && path.resolve(process.argv[1]) === file) {
  const target = path.join(root, 'sdk/scene3d-runtime.generated.ts');
  const digest = scene3dRuntimeHash();
  if (process.argv.includes('--check')) {
    if (!readFileSync(target, 'utf8').includes(`// Source digest: ${digest}\n`))
      throw Error('Shared 3D runtime is stale. Run node tools/scene3d-runtime.mjs.');
  } else {
    const exports = [];
    const license = readFileSync(path.join(threeRoot, 'LICENSE'), 'utf8');
    for (const [name, entry] of [
      ['BROWSER_SCENE3D', 'scene3d-browser.ts'],
      ['NATIVE_SCENE3D_PROXY', 'scene3d-native-proxy.ts'],
    ]) {
      const result = await build({
        root,
        configFile: false,
        logLevel: 'silent',
        define: { 'process.env.NODE_ENV': JSON.stringify('production') },
        build: {
          write: false,
          target: 'es2020',
          minify: true,
          lib: { entry: path.join(root, 'sdk', entry), formats: ['iife'], name: 'GauteScene3d' },
        },
      });
      const code = (Array.isArray(result) ? result : [result])
        .flatMap((r) => r.output)
        .find((f) => f.type === 'chunk').code;
      exports.push(
        `export const ${name} = ${JSON.stringify((name === 'BROWSER_SCENE3D' ? '/* Three.js license\n' + license + '*/\n' : '') + code)};`,
      );
    }
    writeFileSync(
      target,
      `// Generated by tools/scene3d-runtime.mjs. Host code, excluded from game budgets.\n// Source digest: ${digest}\n` +
        exports.join('\n') +
        '\n',
    );
    const formatted = spawnSync(path.join(root, 'node_modules/.bin/vp'), ['fmt', target], {
      stdio: 'inherit',
    });
    if (formatted.status) process.exitCode = formatted.status;
  }
}
